// Phase 3 tables: carts, orders, payments, escrow, ledger, wallets, payouts.
const { ref, str, text, int, num, money, bool, date, en, json } = require("./fields");

const PAYOUT_STATUS = ["PENDING", "PROCESSING", "PAID", "REJECTED", "FAILED"];
const accountDetails = (prefix) => ({
  [`${prefix}.accountName`]: str({ len: 150, required: true }),
  [`${prefix}.accountNumber`]: str({ len: 60, required: true }),
  [`${prefix}.bankName`]: str({ len: 80, default: "MTN MoMo" }),
});
const wallet = (ownerField, collection, model, table, extra = {}) => ({
  model, table, collection,
  fields: {
    [ownerField]: ref("users", { required: true, unique: true, onDelete: "CASCADE" }),
    pendingBalance: money({ required: true, default: 0 }),
    availableBalance: money({ required: true, default: 0 }),
    ...extra,
  },
});
const staffPayout = (ownerField, collection, model, table) => ({
  model, table, collection,
  fields: {
    payoutNumber: str({ len: 60, required: true, unique: true }),
    [ownerField]: ref("users", { required: true, index: true, onDelete: "CASCADE" }),
    amount: money({ required: true }),
    paymentMethod: en(["MOMO", "AIRTEL"], { default: "MOMO" }),
    ...accountDetails("accountDetails"),
    status: en(PAYOUT_STATUS, { default: "PENDING", index: true }),
    transactionReference: str({ len: 120 }),
    rejectionReason: str({ len: 500 }),
    processedAt: date(),
  },
});

